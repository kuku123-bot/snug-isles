// lowercase x is drawn as a multiply sign (used in "x2" style counts)
SRC.x = ['...', '#.#', '.#.', '#.#', '...'];

export const FONT_H = 5;

const GLYPHS = {};
for (const k of Object.keys(SRC)) {
  if (SRC[k].length !== 5 || SRC[k].some((r) => r.length !== 3)) throw new Error('bad glyph ' + k);
  GLYPHS[k] = SRC[k];
}

export const hasGlyph = (ch) => ch in GLYPHS;
export function textWidth(str) {
  return str.length ? str.length * 4 - 1 : 0;
}

/** Render text to a Pixmap, with optional 1px outline (color) and drop shadow. Letters are upper-cased; "x" stays a multiply sign. */
export function renderText(str, color, o = {}) {
  str = String(str);
  const outline = o.outline === undefined ? INK : o.outline; // null = none
  const pad = outline ? 1 : 0;
  const sh = o.shadow ? 1 : 0;
  const pm = new Pixmap(Math.max(1, textWidth(str) + pad * 2 + sh), FONT_H + pad * 2 + sh);
  let x = pad;
  for (const raw of str) {
    const ch = raw === 'x' ? 'x' : raw.toUpperCase();
    const g = GLYPHS[ch] || GLYPHS['?'];
    for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) if (g[r][c] === '#') pm.set(x + c, pad + r, color);
    x += 4;
  }
  if (sh) {
    for (let y = pm.h - 2; y >= 0; y--) for (let xx = pm.w - 2; xx >= 0; xx--) if (pm.isOpaque(xx, y)) pm.under(xx + 1, y + 1, o.shadow);
  }
  if (outline) pm.outline(outline, { diag: true });
  return pm;
}
